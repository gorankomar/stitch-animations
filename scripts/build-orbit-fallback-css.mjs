// Build the nine-dot static fallback from the same allocation/angle helpers as motion.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
const file = new URL('../src/animations/orbit/index.js', import.meta.url);
const source = readFileSync(file, 'utf8').replace(/^import .*;\n/gm, '').replace('export function init', 'function init');
const context = vm.createContext({ setTimeout, clearTimeout });
vm.runInContext(source + '\nthis.helpers={allocateDotsToRings,resolveSpanFactor,computeAngleBounds};', context);
const { allocateDotsToRings, resolveSpanFactor, computeAngleBounds } = context.helpers;
let css = '/* Generated by scripts/build-orbit-fallback-css.mjs. Six prepared native rings; default 3. */\n';
css += '.orbit-graphic .orbit-graphic-ring:nth-child(n+4){display:none}\n';
for (let i = 4; i <= 6; i++) css += `.orbit-graphic .orbit-graphic-ring:nth-child(${i}){--ring-index:${i}}\n`;
for (let count = 1; count <= 6; count++) {
  const root = `.orbit-graphic[data-orbit-rings="${count}"]`;
  css += `${root} .orbit-graphic-wrap{--ring-count:${count}}\n`;
  css += `${root} .orbit-graphic-ring:nth-child(-n+${count}){display:block}\n`;
  css += `${root} .orbit-graphic-ring:nth-child(n+${count + 1}){display:none}\n`;
  if (count === 1) css += `${root} .orbit-graphic-wrap{--ring-base-radius:var(--ring-max-radius)}\n`;
  for (const landscape of [false, true]) {
    const width = landscape ? 564 : 258, height = landscape ? 276 : 232;
    const min = landscape ? 98.5 : 66, max = landscape ? 210.795 : 166;
    const cy = landscape ? 221 : 192, dot = landscape ? 44 : 28;
    const rings = Array.from({ length: count }, (_, i) => ({ radius: count === 1 ? max : min + (max - min) * i / (count - 1), cx: width / 2, cy }));
    const counts = count === 3 ? (landscape ? [2,3,4] : [2,4,3]) : allocateDotsToRings(rings, 9);
    const angles = [[-127.8,-52.2],[-135.9,-90,-44.1],[-158.4,-117,-63,-21.6]];
    const selector = landscape ? `${root}:is(.w-variant-9ca0466f-42cf-4c7e-8753-3cbdd1e476f2,.orbit-graphic--landscape)` : root;
    let cursor = 0;
    rings.forEach((ring, index) => {
      const n = counts[index]; if (!n) return;
      const bounds = computeAngleBounds(ring, dot / 2, width - dot / 2);
      let span = (160 + 20 * (count === 1 ? 1 : index / (count - 1))) * resolveSpanFactor(n);
      if (count === 3) span = (landscape ? [84,102,152] : [80,120,70])[index];
      const available = bounds.right - bounds.left;
      span = Math.max(Math.min(span, available), Math.min(available, 20));
      let start = -90 - span / 2, end = -90 + span / 2;
      if (start < bounds.left) { end += bounds.left - start; start = bounds.left; }
      if (end > bounds.right) { start -= end - bounds.right; end = bounds.right; }
      for (let i = 0; i < n; i++) {
        const angle = landscape && count === 3 ? angles[index][i] : start + (end - start) * (n === 1 ? .5 : i / (n - 1));
        const rad = angle * Math.PI / 180;
        const x = ring.cx + ring.radius * Math.cos(rad), y = ring.cy + ring.radius * Math.sin(rad);
        css += `${selector} .orbit-dots>:nth-child(${++cursor}){left:${(x / width * 100).toFixed(6)}%;top:${(y / height * 100).toFixed(6)}%}\n`;
      }
    });
  }
}
writeFileSync(new URL('../src/embeds/orbit-graphic/ring-count-fallback.css', import.meta.url), css);
