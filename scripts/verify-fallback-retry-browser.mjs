import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Brave Browser.app/Contents/MacOS/Brave Browser'});
const page=await browser.newPage({viewport:{width:1000,height:700}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/fallback-retry-preview.html');
await page.waitForFunction(()=>document.querySelector('[data-fr-dots-ready]'));
const metrics=await page.locator('.fr-frame').evaluateAll(ns=>ns.map(n=>({width:n.clientWidth,height:n.clientHeight,visible:[...n.querySelectorAll('[data-fr-row]')].filter(r=>getComputedStyle(r).visibility==='visible').length})));
assert.deepEqual(metrics.map(n=>n.visible),[4,4]);
assert.ok(metrics.every(n=>Math.abs(n.height/n.width-278/540)<.004));
await page.waitForTimeout(3100);
const scales=await page.locator('[data-fallback-retry]').first().locator('[data-fr-row]').evaluateAll(ns=>ns.map(n=>({scale:new DOMMatrix(getComputedStyle(n).transform).a,opacity:+getComputedStyle(n).opacity})));
for(const i of [1,2,3])assert.equal(scales[i].scale,1);
assert.ok(scales[0].scale<1 && scales[4].scale<1);
await page.evaluate(()=>{const init=window[Symbol.for('stitch.fallback-retry.init')];window.disposeFR=init();init();});
await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(80);
assert.equal(await page.locator('[data-fr-dots-ready]').count(),0);
assert.ok(await page.locator('[data-fr-row]').evaluateAll(ns=>ns.every(n=>n.style.cssText==='')));
await page.evaluate(()=>window.disposeFR());
await page.emulateMedia({reducedMotion:'no-preference'});
await page.evaluate(()=>window[Symbol.for('stitch.fallback-retry.init')]());
await page.waitForFunction(()=>document.querySelector('[data-fr-dots-ready]'));
await page.setViewportSize({width:393,height:700});
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForTimeout(80);await page.screenshot({path:'/tmp/fallback-retry-mobile.png'});
const staticPage=await browser.newPage({javaScriptEnabled:false});await staticPage.goto('http://127.0.0.1:5173/fallback-retry-preview.html');
assert.equal(await staticPage.locator('[data-fr-row]').count(),12);
assert.deepEqual(errors,[]);
await staticPage.screenshot({path:'/tmp/fallback-retry-static.png'});
console.log(JSON.stringify({passed:true,metrics,edgeScales:scales,errors}));await browser.close();
